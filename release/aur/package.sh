#!/bin/sh
# Writes the AUR package wolfpack-bin of a release: package.sh VERSION SUMS DIR, where SUMS is the
# SHA256SUMS.txt of the release. DIR gets PKGBUILD and .SRCINFO, the two files of the AUR
# repository ssh://aur@aur.archlinux.org/wolfpack-bin.git. The workflow `aur.yml` pushes them when
# a release is published. The package installs the archives of the release, which hold only `wolf`,
# and the two license files of the tag.
set -eu
version=$1
sums=$2
dir=$3
here=$(cd "$(dirname "$0")/../.." && pwd)
sum() {
    awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums"
}
file_sum() {
    if command -v sha256sum >/dev/null; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1
}
base="https://github.com/realfamousbae/wolfpack/releases/download/v$version"
raw="https://raw.githubusercontent.com/realfamousbae/wolfpack/v$version"
desc="Statically typed language that compiles to readable TypeScript, Go and Rust"
x64=$(sum wolfpack-linux-x64.tar.gz)
arm64=$(sum wolfpack-linux-arm64.tar.gz)
mit=$(file_sum "$here/LICENSE-MIT")
apache=$(file_sum "$here/LICENSE-APACHE")
if [ -z "$x64" ] || [ -z "$arm64" ]; then
    echo "package.sh: $sums has no sums of the Linux archives" >&2
    exit 1
fi
mkdir -p "$dir"
cat > "$dir/PKGBUILD" <<PKGBUILD
# Generated by release/aur/package.sh of the wolfpack repository for each release.
# Maintainer: Aleksey <223102174+realfamousbae@users.noreply.github.com>
pkgname=wolfpack-bin
pkgver=$version
pkgrel=1
pkgdesc="$desc"
arch=('x86_64' 'aarch64')
url="https://github.com/realfamousbae/wolfpack"
license=('MIT' 'Apache-2.0')
depends=('glibc')
optdepends=('nodejs: the TypeScript target'
            'npm: the TypeScript target'
            'go: the Go target'
            'rust: the Rust target')
provides=('wolfpack')
conflicts=('wolfpack')
options=('!strip' '!debug')
source=("LICENSE-MIT-\$pkgver::$raw/LICENSE-MIT"
        "LICENSE-APACHE-\$pkgver::$raw/LICENSE-APACHE")
source_x86_64=("wolfpack-\$pkgver-x64.tar.gz::$base/wolfpack-linux-x64.tar.gz")
source_aarch64=("wolfpack-\$pkgver-arm64.tar.gz::$base/wolfpack-linux-arm64.tar.gz")
sha256sums=('$mit'
            '$apache')
sha256sums_x86_64=('$x64')
sha256sums_aarch64=('$arm64')

package() {
    install -Dm755 wolf "\$pkgdir/usr/bin/wolf"
    install -Dm644 "LICENSE-MIT-\$pkgver" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE-MIT"
    install -Dm644 "LICENSE-APACHE-\$pkgver" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE-APACHE"
}
PKGBUILD
tab=$(printf '\t')
cat > "$dir/.SRCINFO" <<SRCINFO
pkgbase = wolfpack-bin
${tab}pkgdesc = $desc
${tab}pkgver = $version
${tab}pkgrel = 1
${tab}url = https://github.com/realfamousbae/wolfpack
${tab}arch = x86_64
${tab}arch = aarch64
${tab}license = MIT
${tab}license = Apache-2.0
${tab}depends = glibc
${tab}optdepends = nodejs: the TypeScript target
${tab}optdepends = npm: the TypeScript target
${tab}optdepends = go: the Go target
${tab}optdepends = rust: the Rust target
${tab}provides = wolfpack
${tab}conflicts = wolfpack
${tab}options = !strip
${tab}options = !debug
${tab}source = LICENSE-MIT-$version::$raw/LICENSE-MIT
${tab}source = LICENSE-APACHE-$version::$raw/LICENSE-APACHE
${tab}sha256sums = $mit
${tab}sha256sums = $apache
${tab}source_x86_64 = wolfpack-$version-x64.tar.gz::$base/wolfpack-linux-x64.tar.gz
${tab}sha256sums_x86_64 = $x64
${tab}source_aarch64 = wolfpack-$version-arm64.tar.gz::$base/wolfpack-linux-arm64.tar.gz
${tab}sha256sums_aarch64 = $arm64

pkgname = wolfpack-bin
SRCINFO
